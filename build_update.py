#!/usr/bin/env python3
"""Build the Local Wireless update CIA for Mario Kart Wii 3DS.

Applies local-wireless.patch to an existing, already-built MiniBandit/MKW-3DS
builder folder (v0.7.0), compiles, packages a code-only update CIA into ./out,
then removes the patch again so the builder folder is left as it was.

    python3 build_update.py /path/to/MKW-3DS            clean update CIA
    python3 build_update.py /path/to/MKW-3DS --overlay  with the SELECT debug overlay
"""
import argparse, os, shutil, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PATCH = HERE / "local-wireless.patch"
BASE_VERSION = "0.7.0"
# Generated by the builder from the disc, so not in the patch: one help line only.
HELP_FILE = "include/mkw/menu_assets.hpp"
HELP_OLD = 'UiHelpMainMulti[]={"Race or battle with two players.","Race or battle with three players.","Race or battle with four players."};'
HELP_NEW = 'UiHelpMainMulti[]={' + ",".join(['"Race with nearby 3DS consoles over local wireless (2 to 12 players)."'] * 3) + '};'


def fail(message):
    print(f"\nERROR: {message}")
    sys.exit(1)


def git_apply(builder, *flags):
    return subprocess.run(["git", "apply", "--ignore-whitespace", *flags, str(PATCH)],
                          cwd=builder, capture_output=True, text=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("builder", type=Path, help="your MKW-3DS builder folder (already used to build the game)")
    ap.add_argument("--overlay", action="store_true", help="dev build with the SELECT performance/network overlay")
    ap.add_argument("--keep-patched", action="store_true", help="leave the patch applied afterwards")
    ap.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 2) - 1))
    a = ap.parse_args()

    b = a.builder.expanduser().resolve()
    for need in ("tools/build.py", "tools/release/package_cia.py", "src/main.cpp", HELP_FILE):
        if not (b / need).exists():
            fail(f"{b} is not an MKW-3DS builder folder (missing {need}).")
    version = (b / "tools/release/VERSION").read_text().strip()
    if version != BASE_VERSION:
        fail(f"this patch is for builder {BASE_VERSION}; yours is {version}.")
    if not (b / "build/mkw.shbin").exists() or not (b / "sd-card").exists():
        fail("build the game once with the MiniBandit builder first (its build/ and sd-card/ are needed).")
    if not shutil.which("git"):
        fail("git is required (https://git-scm.com).")

    py = next((str(p) for p in (b / ".venv/bin/python", b / ".venv/Scripts/python.exe") if p.exists()), sys.executable)
    env = dict(os.environ)
    env.setdefault("DEVKITPRO", "C:/devkitPro" if os.name == "nt" else "/opt/devkitpro")
    env.setdefault("DEVKITARM", env["DEVKITPRO"] + "/devkitARM")

    already = git_apply(b, "--check").returncode != 0
    if already and git_apply(b, "-R", "--check").returncode != 0:
        fail("the patch does not apply: the builder's sources differ from MiniBandit/MKW-3DS "
             f"{BASE_VERSION} (commit {(HERE / 'BASE_COMMIT').read_text().strip()[:7]}).")
    help_path = b / HELP_FILE
    help_text = help_path.read_text(encoding="utf-8")

    try:
        if not already:
            r = git_apply(b)
            if r.returncode:
                fail("git apply failed:\n" + r.stderr)
            print("Patch applied.")
        if HELP_OLD in help_text:
            help_path.write_text(help_text.replace(HELP_OLD, HELP_NEW), encoding="utf-8")

        build = [py, "tools/build.py", "--jobs", str(a.jobs)] + ([] if a.overlay else ["--release"])
        print("\n== compiling ==\n" + " ".join(build))
        if subprocess.run(build, cwd=b, env=env).returncode:
            fail("compilation failed (see above).")

        out = HERE / "out"
        out.mkdir(exist_ok=True)
        cia = out / ("MKW-3DS-LocalWireless-Update" + ("-overlay" if a.overlay else "") + ".cia")
        print("\n== packaging update CIA ==")
        if subprocess.run([py, "tools/release/package_cia.py", "--update", "--output", str(cia)],
                          cwd=b, env=env).returncode or not cia.exists():
            fail("packaging failed (see above).")
        print(f"\nDone: {cia}\nInstall it with FBI over the game on every console that will play.")
    finally:
        if not a.keep_patched and not already:
            if git_apply(b, "-R", "--check").returncode == 0:
                git_apply(b, "-R")
            help_path.write_text(help_text, encoding="utf-8")
            print("Builder folder restored.")


if __name__ == "__main__":
    main()
